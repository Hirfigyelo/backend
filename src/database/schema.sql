-- Articles
CREATE TABLE articles {
	articleID INTEGER PRIMARY KEY,
	views INTEGER NOT NULL DEFAULT 0,
	title VARCHAR(255) NOT NULL,
	summary TEXT NOT NULL
};

CREATE TABLE categories {
	categoryID INTEGER PRIMARY KEY,
	name VARCHAR(255) NOT NULL UNIQUE
};

CREATE TABLE article_categories {
	categoryID INTEGER NOT NULL,
	articleID INTEGER NOT NULL,
	PRIMARY KEY (articleID, categoryID),
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE,
	FOREIGN KEY (categoryID) REFERENCES categories(categoryID) ON DELETE CASCADE
};

CREATE TABLE article_attachments {
	articleID INTEGER NOT NULL,
	attachmentID TEXT NOT NULL,
	PRIMARY KEY (articleID, attachmentID),
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE
	FOREIGN KEY (attachmentID) REFERENCES article_media(imageID) ON DELETE CASCADE
};

CREATE TABLE article_media {
	imageID INTEGER PRIMARY KEY,
	path TEXT NOT NULL,
	alt TEXT NOT NULL,
	title TEXT NOT NULL,
};

CREATE TABLE article_comments {
	commentID INTEGER PRIMARY KEY,
	replyTo INTEGER,
	articleID INTEGER NOT NULL,
	userID INTEGER NOT NULL,
	comment TEXT NOT NULL,
	timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	edited_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE,
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
	FOREIGN KEY (replyTo) REFERENCES article_comments(commentID) ON DELETE CASCADE
};

CREATE TABLE article_ratings {
	userID INTEGER NOT NULL,
	articleID INTEGER NOT NULL,
	rating INTEGER NOT NULL,
	PRIMARY KEY (userID, articleID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE,
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE
};

CREATE TABLE portals {
	portalID INTEGER PRIMARY KEY,
	domain VARCHAR(255) NOT NULL UNIQUE,
	name VARCHAR(255) NOT NULL,
	icon VARCHAR(255) NOT NULL
};

CREATE TABLE authors {
	authorID INTEGER PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	portalID INTEGER NOT NULL,

	FOREIGN KEY (portalID) REFERENCES portals(portalID) ON DELETE CASCADE
};

CREATE TABLE external_articles {
	articleID INTEGER NOT NULL,
	version INTEGER NOT NULL,
	title VARCHAR(255) NOT NULL,
	summary TEXT NOT NULL,
	bias INTEGER NOT NULL DEFAULT 0,
	content TEXT NOT NULL,
	content_hash VARCHAR(255) NOT NULL,
	url VARCHAR(255) NOT NULL,
	parsed_at TIMESTAMP NOT NULL,
	published_at TIMESTAMP NOT NULL,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	portalID INTEGER NOT NULL,
	authorID INTEGER NOT NULL,

	PRIMARY KEY (articleID, version),
	FOREIGN KEY (portalID) REFERENCES portals(portalID) ON DELETE CASCADE,
	FOREIGN KEY (authorID) REFERENCES authors(authorID) ON DELETE CASCADE
};

CREATE TABLE article_connections {
	internalID INTEGER NOT NULL,
	externalID INTEGER NOT NULL,

	PRIMARY KEY (internalID, externalID),
	FOREIGN KEY (internalID) REFERENCES articles(articleID) ON DELETE CASCADE,
	FOREIGN KEY (externalID) REFERENCES external_articles(articleID) ON DELETE CASCADE
};
-- Users
CREATE TABLE users {
	userID INTEGER PRIMARY KEY,
	username VARCHAR(255) NOT NULL,
	email VARCHAR(255) NOT NULL UNIQUE,
	password_hash VARCHAR(255) NOT NULL,
	allowed INTEGER NOT NULL DEFAULT 1,
	verified_email INTEGER NOT NULL DEFAULT 0,
	admin INTEGER NOT NULL DEFAULT 0,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
};

CREATE TABLE logs {
	logID INTEGER PRIMARY KEY,
	userID INTEGER NOT NULL,
	url TEXT NOT NULL,
	timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
};

CREATE TABLE user_sessions {
	sessionID TEXT PRIMARY KEY,
	userID INTEGER NOT NULL,
	user-agent TEXT NOT NULL,
	IP_address TEXT NOT NULL,
	allowed INTEGER NOT NULL DEFAULT 1,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	last_used_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
};

CREATE TABLE user_remember {
	sessionID TEXT PRIMARY KEY,
	userID INTEGER NOT NULL,
	token TEXT NOT NULL,

	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
	FOREIGN KEY (sessionID) REFERENCES user_sessions(sessionID) ON DELETE CASCADE
};

CREATE TABLE user_pw_reset {
	resetID TEXT PRIMARY KEY,
	userID INTEGER NOT NULL,
	used INTEGER NOT NULL DEFAULT 0,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
};

CREATE TABLE user_favorites {
	articleID INTEGER NOT NULL,
	userID INTEGER NOT NULL,

	PRIMARY KEY (articleID, userID),
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE,
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
};

CREATE TABLE user_email_verification {
	verificationID TEXT PRIMARY KEY,
	userID INTEGER NOT NULL,
	used INTEGER NOT NULL DEFAULT 0,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE
};

CREATE TABLE user_history {
	userID INTEGER NOT NULL,
	articleID INTEGER NOT NULL,

	viewed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (userID, articleID),
	FOREIGN KEY (userID) REFERENCES users(userID) ON DELETE CASCADE,
	FOREIGN KEY (articleID) REFERENCES articles(articleID) ON DELETE CASCADE
};
